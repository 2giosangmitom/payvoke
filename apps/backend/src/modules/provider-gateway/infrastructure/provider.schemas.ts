import { EntitySchema } from "@mikro-orm/core";
import {
  CommandInvocation,
  CommandRevision,
  ProviderApiKey,
  ProviderApplication,
} from "../domain/provider.js";

export const providerGatewaySchemas = [
  new EntitySchema({
    class: ProviderApplication,
    tableName: "provider_applications",
    rowLevelSecurity: true,
    properties: {
      id: { type: "uuid", primary: true },
      providerId: {
        kind: "m:1",
        type: "ProviderProfile",
        fieldName: "provider_id",
        mapToPk: true,
        index: true,
        deleteRule: "cascade",
      },
      name: { type: "string", length: 100 },
      currentRevisionId: { type: "uuid", nullable: true },
      sessionId: { type: "uuid", nullable: true },
      sessionExpiresAt: { type: "datetime", nullable: true },
      createdAt: { type: "datetime" },
    },
  }),
  new EntitySchema({
    class: ProviderApiKey,
    tableName: "provider_api_keys",
    rowLevelSecurity: true,
    properties: {
      id: { type: "uuid", primary: true },
      applicationId: {
        kind: "m:1",
        type: "ProviderApplication",
        fieldName: "application_id",
        mapToPk: true,
        index: true,
        deleteRule: "cascade",
      },
      label: { type: "string", length: 100 },
      hash: { type: "string", length: 64, unique: true },
      prefix: { type: "string", length: 12 },
      scopes: { type: "json" },
      expiresAt: { type: "datetime" },
      revokedAt: { type: "datetime", nullable: true },
      createdAt: { type: "datetime" },
    },
  }),
  new EntitySchema({
    class: CommandRevision,
    tableName: "provider_command_revisions",
    rowLevelSecurity: true,
    uniques: [{ properties: ["applicationId", "digest"] }],
    properties: {
      id: { type: "uuid", primary: true },
      applicationId: {
        kind: "m:1",
        type: "ProviderApplication",
        fieldName: "application_id",
        mapToPk: true,
        index: true,
        deleteRule: "cascade",
      },
      digest: { type: "string", length: 64 },
      commands: { type: "json" },
      createdAt: { type: "datetime" },
    },
  }),
  new EntitySchema({
    class: CommandInvocation,
    tableName: "provider_command_invocations",
    rowLevelSecurity: true,
    checks: [{ expression: "state in ('queued', 'running', 'completed', 'failed', 'uncertain')" }],
    properties: {
      id: { type: "uuid", primary: true },
      applicationId: {
        kind: "m:1",
        type: "ProviderApplication",
        fieldName: "application_id",
        mapToPk: true,
        index: true,
        deleteRule: "cascade",
      },
      revisionId: {
        kind: "m:1",
        type: "CommandRevision",
        fieldName: "revision_id",
        mapToPk: true,
        deleteRule: "cascade",
      },
      conversationId: {
        kind: "m:1",
        type: "Conversation",
        fieldName: "conversation_id",
        mapToPk: true,
        nullable: true,
        index: true,
        deleteRule: "cascade",
      },
      listingVersionId: {
        kind: "m:1",
        type: "ManifestVersion",
        fieldName: "listing_version_id",
        mapToPk: true,
        nullable: true,
        deleteRule: "cascade",
      },
      command: { type: "string", length: 32 },
      input: { type: "json" },
      executorId: { type: "uuid", nullable: true },
      state: { type: "string", length: 16 },
      progress: { type: "text", nullable: true },
      result: { type: "text", nullable: true },
      terminalDigest: { type: "string", length: 64, nullable: true },
      deadlineAt: { type: "datetime" },
      createdAt: { type: "datetime" },
    },
  }),
];
